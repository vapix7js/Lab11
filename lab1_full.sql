DROP TABLE IF EXISTS prepodavateli CASCADE;
DROP TABLE IF EXISTS kafedry CASCADE;

CREATE TABLE kafedry (
    nomer_kafedry INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kod_fakulteta INTEGER NOT NULL,
    nazvanie VARCHAR(100) NOT NULL,
    vypuskayushchaya BOOLEAN NOT NULL,
    sait VARCHAR(255),
    telefon VARCHAR(20)
);

CREATE TABLE prepodavateli (
    kod_prepodavatelya INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    familiya VARCHAR(50) NOT NULL,
    imya VARCHAR(50) NOT NULL,
    otchestvo VARCHAR(50),
    obrazovanie VARCHAR(100),
    stazh INTEGER NOT NULL CHECK (stazh >= 0),
    nomer_kafedry INTEGER NOT NULL,
    telefon VARCHAR(20),
    CONSTRAINT fk_prepodavateli_kafedry
        FOREIGN KEY (nomer_kafedry)
        REFERENCES kafedry (nomer_kafedry)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

